// generateProtocol.mjs — src/hostProtocol.generated.ts from schema/hostProtocol.schema.json, through quicktype.
// A dev-time generator, run by `npm run generate`: the output is committed, so no build or CI ever fetches quicktype.

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const QUICKTYPE = "quicktype@26.0.0";
const FRAMES = [
  "StateFrame",
  "NotifyFrame",
  "ResultFrame",
  "EngineFrame",
  "CommandLine",
];

const pkg = join(dirname(fileURLToPath(import.meta.url)), "..");
// One source per frame: quicktype would merge a `oneOf` of objects into one interface of optional fields.
const sources = FRAMES.map(
  (f) => `schema/hostProtocol.schema.json#/definitions/${f}`,
);
const out = execFileSync(
  "npx",
  [
    "--yes",
    QUICKTYPE,
    "--src-lang",
    "schema",
    "--lang",
    "typescript",
    "--just-types",
    "--prefer-unions",
    "--prefer-const-values",
    "--no-combine-classes",
    ...sources,
  ],
  { cwd: pkg, encoding: "utf8" },
);
const header = `// hostProtocol.generated.ts — GENERATED by scripts/generateProtocol.mjs (${QUICKTYPE}) from schema/hostProtocol.schema.json.\n// Do not edit: change the schema and run \`npm run generate\`.\n\n`;
writeFileSync(join(pkg, "src/hostProtocol.generated.ts"), header + out);
