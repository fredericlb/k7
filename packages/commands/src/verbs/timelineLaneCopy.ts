// timelineLaneCopy.ts — `timeline lane copy`: a lane's events copied onto a new lane of another
// timeline, or of the song. What a reader gets wrong: it copies EVENTS — references to the same
// clips — and nothing that sounds; a song lane made from it gets an empty chain and a fresh strip.
// See @studio/song docs/timelines.md.

import { join } from "node:path";
import { K7Document } from "@studio/k7x/document";
import { laneEventsAt } from "@studio/song/chainItemEdit";
import { loadGraph } from "@studio/song/graph";
import { createTrackFile } from "@studio/song/loader";
import { addTrackMixer } from "@studio/song/trackMixerFile";
import { wsData, wsEdit, wsText } from "@studio/song/yaml/workspaceDoc";
import { wsExists } from "@studio/song/yaml/workspaceFile";
import { addTrackPlacements } from "@studio/song-edit/trackMix";
import { splitPort } from "@studio/song-schema/moduleTypes";
import { SONG_TARGET, timelineLaneOf } from "@studio/song-schema/timelineLane";
import type { Placement } from "@studio/song-schema/yaml/placementSchema";
import { placementValues } from "@studio/song-schema/yaml/trackFile";
import type { SidHandler } from "../commands.ts";
import { makesCycle, splitArgs, trackOf } from "./shared.ts";

const NAME = /^[A-Za-z0-9_.-]+$/;

/** `base`, or `base-2`, `base-3`… — the first that `taken` does not hold. */
function freeName(base: string, taken: Set<string>): string {
  if (!taken.has(base)) return base;
  let n = 2;
  while (taken.has(`${base}-${n}`)) n++;
  return `${base}-${n}`;
}

export const TIMELINE_LANE_COPY_VERBS: Record<string, SidHandler> = {
  /** timeline lane copy <lane> <timeline|song> [name] — the lane's events onto a new lane there; docs/verbs.md. */
  "timeline.laneCopy": async (a, h) => {
    const [laneArg, to, name] = splitArgs(a);
    if (!laneArg || !to)
      return h.refuse([
        "usage: timeline lane copy <lane> <timeline|song> [name]  (e.g. timeline lane copy verse>drums chorus)",
      ]);
    const p = h.project();
    const track = trackOf(p, laneArg);
    if (!track) return h.refuse([`no track "${laneArg}"`]);
    if (track.generated)
      return h.refuse([
        `'${track.id}' is generated by a pattern and holds no events to copy`,
      ]);
    const inTimeline = timelineLaneOf(track.id);
    // A song lane wired on two ports is two engine tracks; its events are the LANE's.
    const lane = inTimeline ? track.id : splitPort(track.id).node;
    const label = inTimeline?.lane ?? lane;
    const at = laneEventsAt(h.songPath, lane);
    if (!at) return h.refuse([`'${lane}' has no file to copy from`]);
    const events = placementValues(
      new K7Document(wsText(at.path)).at(at.base),
    ) as Placement[];

    if (to === SONG_TARGET) {
      if (!inTimeline)
        return h.refuse([
          `'${lane}' is already the song's — track duplicate copies a song lane, chain and all`,
        ]);
      const taken = new Set(p.tracks.map((t) => splitPort(t.id).node));
      const id = name ?? freeName(label, taken);
      if (!NAME.test(id) || taken.has(id))
        return h.refuse([
          `'${id}' cannot name a new song lane — taken, or not a name`,
        ]);
      try {
        const written = createTrackFile(h.songPath, id);
        let strip: string[] = [];
        try {
          strip = addTrackMixer(h.songPath, id, loadGraph(h.songPath)) ?? [];
        } catch {}
        if (events.length) addTrackPlacements(h.songPath, id, events);
        h.log([
          `+ track ${id}: ${events.length} event(s) of ${track.id} (${[...written, ...strip].join(", ")})`,
        ]);
        await h.reload();
      } catch (e) {
        h.refuse([`timeline lane copy failed: ${(e as Error).message}`]);
      }
      return;
    }

    const file = join(h.songPath, "timelines", `${to}.k7x`);
    if (!wsExists(file))
      return h.refuse([
        `no timeline "${to}" — name a timeline of timelines/, or ${SONG_TARGET}`,
      ]);
    const lanes = wsData(file).lanes;
    const taken = new Set(
      (Array.isArray(lanes) ? lanes : []).map((l) =>
        String((l as { lane?: unknown })?.lane),
      ),
    );
    const id = name ?? freeName(label, taken);
    if (!NAME.test(id) || taken.has(id))
      return h.refuse([
        `'${id}' cannot name a new lane of '${to}' — taken, or not a name`,
      ]);
    // A copy holding `to` itself, directly or not, would play it inside itself.
    const loop = events.find((e) =>
      makesCycle(p, `${to}>${id}`, String(e.ref ?? "")),
    );
    if (loop)
      return h.refuse([
        `'${track.id}' places timeline '${loop.ref}', which would then play inside '${to}'`,
      ]);
    wsEdit(file, (doc) => doc.addIn(["lanes"], { lane: id, events }));
    h.log([`${to}: + lane ${id}, ${events.length} event(s) of ${track.id}`]);
    await h.reload();
  },
};
