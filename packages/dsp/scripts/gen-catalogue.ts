// gen-catalogue.ts — walk modules/ and write src/catalogue.generated.ts, the seed a brand-new
// `@st0` library repository is filled with. Run it after adding or editing a module here, and
// COMMIT the output: `npm run gen:catalogue --workspace @studio/dsp`.
//
// The generator exists for one reason — `@studio/file-service` is esbuilt into a single .mjs
// inside the tray, so it cannot read this folder at runtime. See packages/dsp/docs/catalogue.md.

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "modules");
const out = join(here, "..", "src", "catalogue.generated.ts");

/**
 * What a module folder may hold, and nothing else.
 *
 * An allow-list rather than a skip-list, because the failure of the other shape is silent: a
 * `.DS_Store` or an editor's swap file would be committed into everybody's library, and a `.wav`
 * somebody dropped in would be embedded — as mojibake, since everything here is read as UTF-8.
 * Anything unlisted is REPORTED and left out, so adding a kind of file is a deliberate act.
 */
const KEEP = new Set([
  "module.yaml",
  "ui.yaml",
  "presets.yaml",
  "jsdsp.ts",
  "jsdsp.json",
  "dsp.dsp",
]);

const files: string[] = [];
const skipped: string[] = [];
const walk = (dir: string): void => {
  for (const e of readdirSync(dir).sort()) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) walk(p);
    else if (KEEP.has(e)) files.push(p);
    else skipped.push(relative(root, p));
  }
};
walk(root);

// Forward slashes, always: these become paths in a git repository on three platforms, and
// `\` in one would be a filename rather than a folder on the other two.
const entries = files
  .map(
    (abs) =>
      [
        relative(root, abs).split(sep).join("/"),
        readFileSync(abs, "utf8"),
      ] as const,
  )
  .map(([path, text]) => `  ${JSON.stringify(path)}: ${JSON.stringify(text)},`)
  .join("\n");

writeFileSync(
  out,
  `// GENERATED by scripts/gen-catalogue.ts — do not edit. Run\n` +
    `// \`npm run gen:catalogue --workspace @studio/dsp\` and commit the result.\n` +
    `//\n` +
    `// The modules a brand-new @st0 library repository is seeded with, keyed by their path\n` +
    `// INSIDE that repository's \`modules/\` folder. See packages/dsp/docs/catalogue.md.\n` +
    `\n` +
    `export const CATALOGUE: Record<string, string> = {\n${entries}\n};\n`,
  "utf8",
);

console.log(`wrote ${out}  (${files.length} files)`);
// Loud, not silent: a module whose panel was left out of the seed draws as a module with no face
// in everybody's library, and nothing downstream can tell that from one that never had a panel.
if (skipped.length)
  console.warn(
    `  NOT in the catalogue (unlisted kind — see KEEP):\n    ${skipped.join("\n    ")}`,
  );
