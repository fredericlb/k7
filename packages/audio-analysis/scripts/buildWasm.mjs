// buildWasm.mjs — builds rust/ for wasm32 and writes it into src/waveformWasm.generated.ts, base64, with the hash of its sources.
// A reader would get wrong why the module is checked in: the file service loads this package as raw TypeScript, with no build step.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { rustSourceHash } from "./rustSources.mjs";

const PKG = join(import.meta.dirname, "..");
const RUST = join(PKG, "rust");
const TARGET = "wasm32-unknown-unknown";

execFileSync("cargo", ["build", "--release", "--lib", "--target", TARGET], {
  cwd: RUST,
  stdio: "inherit",
});
const wasm = readFileSync(
  join(RUST, "target", TARGET, "release", "waveform.wasm"),
);
const out = join(PKG, "src", "waveformWasm.generated.ts");
writeFileSync(
  out,
  `// waveformWasm.generated.ts — GENERATED by scripts/buildWasm.mjs from rust/: the waveform measure as WebAssembly. Do not edit.\n` +
    `// ${wasm.length} bytes. A test fails when rust/ no longer hashes to SOURCES: re-run \`npm run build:wasm -w @studio/audio-analysis\`.\n\n` +
    `export const SOURCES = "${rustSourceHash()}";\n\n` +
    `export const WASM = "${wasm.toString("base64")}";\n`,
);
console.log(`${out}: ${wasm.length} bytes`);
