// gen-builtin-params.mjs — ask the engine what every built-in plugin's parameters are, and write the
// table @studio/song ships. Run it after bumping Tracktion or adding a built-in; the file it writes is
// generated and committed, so no build step depends on a C++ binary. See docs/builtinParams.md.

import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const moteur = join(here, "..");
const OUT = join(
  moteur,
  "..",
  "..",
  "packages",
  "song-schema",
  "src",
  "builtinParams.generated.ts",
);

/** Wherever the current platform's preset put the binary. First one that exists wins. */
function engineBinary() {
  const candidates = [
    "build/windows-msvc/RelWithDebInfo/studio-moteur.exe",
    "build/macos-clang/studio-moteur",
    "build/dev-gcc/studio-moteur",
    "build/dev-clang/studio-moteur",
    "build/release-gcc/studio-moteur",
  ].map((p) => join(moteur, p));
  const found = candidates.find((p) => existsSync(p));
  if (!found)
    throw new Error(
      `no studio-moteur binary — build it first (npm run build:win|build:mac --workspace moteur).\nLooked in:\n  ${candidates.join("\n  ")}`,
    );
  return found;
}

const BEGIN = "STUDIO_PARAMS_BEGIN";
const END = "STUDIO_PARAMS_END";

const raw = execFileSync(engineBinary(), ["--dump-builtin-params"], {
  encoding: "utf8",
  maxBuffer: 64 * 1024 * 1024,
});
const from = raw.indexOf(BEGIN);
const to = raw.indexOf(END);
if (from < 0 || to < 0)
  throw new Error(`no sentinels in the engine's output:\n${raw.slice(0, 400)}`);
const table = JSON.parse(raw.slice(from + BEGIN.length, to).trim());

/** A number as TypeScript source. Ranges come out of C++ as doubles; keep them short and exact. */
const num = (v) => (Number.isInteger(v) ? String(v) : String(Number(v.toPrecision(10))));
const str = (s) => JSON.stringify(s);

const lines = [];
let plugins = 0;
let params = 0;
for (const [type, info] of Object.entries(table)) {
  plugins++;
  lines.push(`  ${str(type)}: {`);
  lines.push(`    name: ${str(info.name)},`);
  lines.push(`    role: ${str(info.role)},`);
  if (!info.params.length) {
    // Kept rather than dropped: "this plugin has none" and "we have never asked" are different
    // answers, and only the first one lets a panel say so instead of looking unfinished.
    lines.push("    params: [],");
    lines.push("  },");
    continue;
  }
  lines.push("    params: [");
  for (const p of info.params) {
    params++;
    const bits = [
      `name: ${str(p.name)}`,
      `min: ${num(p.min)}`,
      `max: ${num(p.max)}`,
    ];
    if (p.def !== null && p.def !== undefined) bits.push(`def: ${num(p.def)}`);
    if (p.states?.length)
      bits.push(
        `states: [${p.states.map((s) => `{ label: ${str(s.label)}, value: ${num(s.value)} }`).join(", ")}]`,
      );
    lines.push(`      { ${bits.join(", ")} },`);
  }
  lines.push("    ],");
  lines.push("  },");
}

const source = `// GENERATED by engine/moteur/scripts/gen-builtin-params.mjs — do not edit by hand.
//
// Every built-in plugin the engine can create, and the parameters each one HAS: read out of a real
// instance, because a plugin registers its parameters in its constructor (4OSC calls addParam 68
// times there) and no static reading of the source can be trusted to keep up. Re-run the script
// after bumping Tracktion or adding a built-in. See engine/moteur/docs/builtinParams.md.
//
// ${plugins} plugins, ${params} parameters.

import type { BuiltinPluginInfo } from "./builtinParams";

/** Keyed by xmlTypeName, which is what \`createNewPlugin\` takes. A module may name a built-in by this OR by
 *  its display name — \`builtinPluginFor\` accepts both, exactly as the engine's \`resolveBuiltInType\` does. */
export const BUILTIN_PLUGINS: Record<string, BuiltinPluginInfo> = {
${lines.join("\n")}
};
`;

writeFileSync(OUT, source, "utf8");
console.log(`${OUT}: ${plugins} plugins, ${params} parameters`);
