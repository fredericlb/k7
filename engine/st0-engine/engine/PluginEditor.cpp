// Extract the icon embedded in a plugin binary, best-effort — where it looks, and why the DIB is top-down: docs/pluginEditors.md.
juce::Image windowsFileIcon(const juce::File& pluginFile) {
    juce::File target = pluginFile;
    if (target.isDirectory()) {
        auto arch = target.getChildFile("Contents").getChildFile("x86_64-win");
        juce::Array<juce::File> mods;
        if (arch.isDirectory())
            arch.findChildFiles(mods, juce::File::findFiles, false, "*.vst3");
        if (mods.isEmpty()) return {};
        target = mods.getReference(0);
    }

    HICON hIcon = nullptr;
    if (ExtractIconExW(target.getFullPathName().toWideCharPointer(), 0, &hIcon, nullptr, 1) == 0
        || hIcon == nullptr)
        return {};

    constexpr int sz = 32;
    juce::Image img(juce::Image::ARGB, sz, sz, true);
    BITMAPINFO bi{};
    bi.bmiHeader.biSize = sizeof(BITMAPINFOHEADER);
    bi.bmiHeader.biWidth = sz;
    bi.bmiHeader.biHeight = -sz;   // top-down
    bi.bmiHeader.biPlanes = 1;
    bi.bmiHeader.biBitCount = 32;
    bi.bmiHeader.biCompression = BI_RGB;
    void* bits = nullptr;
    HDC screen = GetDC(nullptr);
    HDC mem = CreateCompatibleDC(screen);
    HBITMAP dib = CreateDIBSection(screen, &bi, DIB_RGB_COLORS, &bits, nullptr, 0);
    auto* old = SelectObject(mem, dib);
    DrawIconEx(mem, 0, 0, hIcon, sz, sz, 0, nullptr, DI_NORMAL);
    GdiFlush();   // flush the batch before reading the DIB bits directly

    const auto* px = static_cast<const juce::uint32*>(bits);
    bool anyAlpha = false;
    for (int i = 0; i < sz * sz; ++i)
        if ((px[i] >> 24) != 0) { anyAlpha = true; break; }

    juce::Image::BitmapData data(img, juce::Image::BitmapData::writeOnly);
    for (int y = 0; y < sz; ++y)
        for (int x = 0; x < sz; ++x) {
            const juce::uint32 p = px[y * sz + x];   // BGRA in memory
            const auto b = (juce::uint8) p, g = (juce::uint8)(p >> 8), r = (juce::uint8)(p >> 16);
            auto a = (juce::uint8)(p >> 24);
            if (!anyAlpha) a = (r || g || b) ? 255 : 0;   // pre-Vista icons carry no alpha
            data.setPixelColour(x, y, juce::Colour(r, g, b, a));
        }

    SelectObject(mem, old);
    DeleteObject(dib);
    DeleteDC(mem);
    ReleaseDC(nullptr, screen);
    DestroyIcon(hIcon);
    return img;
}
