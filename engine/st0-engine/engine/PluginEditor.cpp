// st0's own icon, compiled in: the DEFAULT when a plugin brings none, cached so repeated opens do not re-decode the PNG.
juce::Image studioIcon() {
    return juce::ImageCache::getFromMemory(BinaryData::studio_icon_png, BinaryData::studio_icon_pngSize);
}

// A best-effort icon matching a plugin: its VST3 "snapshot" first, else the icon in its binary; an invalid Image means nothing was found.
juce::Image pluginIconFor(const juce::PluginDescription& desc) {
    const juce::File file(desc.fileOrIdentifier);

    // VST3 snapshot: <bundle>/Contents/Resources/Snapshots/<classID>_snapshot(.2.0x).png
    if (file.isDirectory()) {
        auto snaps = file.getChildFile("Contents").getChildFile("Resources").getChildFile("Snapshots");
        if (snaps.isDirectory()) {
            juce::Array<juce::File> pngs;
            snaps.findChildFiles(pngs, juce::File::findFiles, false, "*.png");
            juce::File best;
            for (auto& f : pngs)   // prefer the hi-dpi @2x variant when present
                if (best == juce::File() || f.getFileName().containsIgnoreCase("2.0x"))
                    best = f;
            if (best != juce::File())
                if (auto img = juce::ImageFileFormat::loadFrom(best); img.isValid())
                    return img;
        }
    }

#if JUCE_WINDOWS
    if (auto img = windowsFileIcon(file); img.isValid())
        return img;
#endif

    return {};
}

// Show a plugin window, front it, and hand focus to its editor — the always-on-top toggle is explained in docs/pluginEditors.md.
void raiseToFront(juce::Component& w) {
    w.setVisible(true);
    w.setAlwaysOnTop(true);
    w.toFront(true);         // bring to front + request keyboard focus
    w.setAlwaysOnTop(false); // release, but keep the top-of-z-order position
    w.grabKeyboardFocus();   // route focus into the editor content
}

// A top-level window owning a plugin's native editor; it HIDES rather than destroys on close, and `save_` autosaves — docs/pluginEditors.md.
class PluginWindow : public juce::DocumentWindow, private juce::Timer {
public:
    static constexpr int autosaveMs = 5000;

    PluginWindow(const juce::String& title, juce::AudioProcessorEditor* editor,
                 const juce::Image& icon, std::function<void()> save)
        : juce::DocumentWindow(title, juce::Colours::darkgrey, juce::DocumentWindow::allButtons),
          save_(std::move(save)) {
        setUsingNativeTitleBar(true);
        setContentOwned(editor, true);       // window owns + deletes the editor
        setResizable(editor->isResizable(), false);
        centreWithSize(getWidth(), getHeight());
        if (icon.isValid())
            setIcon(icon);                   // the plugin's own icon in the title bar / taskbar
        raiseToFront(*this);                 // show, bring to front, focus the editor (starts the timer)
    }

    // Hide instead of destroy: the next open is a visibility flip, and a final save persists the last tweak.
    void closeButtonPressed() override {
        setVisible(false);
        if (save_)
            save_();
    }

private:
    // Autosave only while on screen — a hidden window has nothing new to persist; setVisible drives the timer.
    void visibilityChanged() override {
        if (isVisible())
            startTimer(autosaveMs);
        else
            stopTimer();
    }
    void timerCallback() override {
        if (save_)
            save_();
    }

    std::function<void()> save_;
};

