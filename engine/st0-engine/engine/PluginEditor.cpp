// Owns the plugin-editor windows and the param/preset persistence; stateless beyond its Impl&, so EngineHost builds a temporary per call.
class PluginEditorController {
public:
    // A controller serves ONE session, resolved once and never CREATED — a null `sess_` reads as "no such plugin" (docs/pluginEditors.md).
    PluginEditorController(EngineHost::Impl& impl, std::string session)
        : impl_(impl), session_(std::move(session)), sess_(impl.find(session_)) {}

    void show(const std::string& id);
    void setParam(const std::string& id, const std::string& name, double value);
    std::vector<std::pair<std::string, double>> params(const std::string& id) const;
    void persist(const std::string& id);
    void watch(const std::string& id, bool on);
    void pumpWatches();
    std::vector<EngineHost::PresetInfo> listPresets(const std::string& module);
    void setPreset(const std::string& module, int programIndex, const std::string& presetPath);

private:
    // The live external instances of a module — pluginsById is keyed "<chain>:<module>", and one module reused across chains has several.
    std::vector<std::pair<std::string, te::ExternalPlugin*>> moduleInstances(
        const std::string& module) const;

    EngineHost::Impl& impl_;
    std::string session_;
    Session* sess_;
};

// Deliberately silent, unlike applyPluginParams: a control drag calls this at interactive rates, and a wrong name surfaces on the next apply.
void PluginEditorController::setParam(const std::string& id, const std::string& name, double value) {
    if (sess_ == nullptr) return;
    auto it = sess_->pluginsById.find(id);
    if (it == sess_->pluginsById.end() || it->second == nullptr)
        return;
    if (name == kMixParam) return setModuleMix(*it->second, value);
    if (name == kInputVolumeParam) return setModuleInputDb(*it->second, value);
    if (name == kOutputVolumeParam) return setModuleOutputDb(*it->second, value);
    // Held since the engine's stage replaces it: a knob on it would fight the stage — docs/mix.md.
    if (heldByStage(*it->second, name)) {
        warn("'" + name + "' is held by the engine's own stage: turn its @mix, @input-volume or @output-volume instead", id);
        return;
    }
    // pluginParams, not namedParams: a built-in registering nothing is addressed through its ValueTree properties.
    for (const auto& p : pluginParams(*it->second))
        if (p.name.toStdString() == name) {
            p.set(value);
            return;
        }
}

std::vector<std::pair<std::string, double>> PluginEditorController::params(const std::string& id) const {
    if (sess_ == nullptr) return {};
    auto it = sess_->pluginsById.find(id);
    if (it == sess_->pluginsById.end() || it->second == nullptr)
        return {};
    return allParams(*it->second);
}

void PluginEditorController::watch(const std::string& id, bool on) {
    if (sess_ == nullptr) return;
    if (on)
        sess_->watchedParams.emplace(id, std::map<std::string, double>{});
    else
        sess_->watchedParams.erase(id);
}

// Sample every watched plugin and report the ones that moved, against what was last REPORTED — docs/pluginEditors.md.
void PluginEditorController::pumpWatches() {
    if (!impl_.pluginParamsLiveCb || sess_ == nullptr)
        return;
    for (auto& [id, lastSent] : sess_->watchedParams) {
        auto it = sess_->pluginsById.find(id);
        if (it == sess_->pluginsById.end() || it->second == nullptr)
            continue;   // watched but not (yet) in the edit — a rebuild will bring it back
        auto current = allParams(*it->second);
        bool changed = current.size() != lastSent.size();
        if (!changed)
            for (const auto& [name, value] : current) {
                auto prev = lastSent.find(name);
                if (prev == lastSent.end() || prev->second != value) {
                    changed = true;
                    break;
                }
            }
        if (!changed)
            continue;
        lastSent.clear();
        for (const auto& [name, value] : current)
            lastSent.emplace(name, value);
        impl_.pluginParamsLiveCb(session_, id, current);
    }
}

void PluginEditorController::show(const std::string& id) {
    if (sess_ == nullptr) {
        warn("no such plugin in the running edit", id);
        return;
    }
    auto it = sess_->pluginsById.find(id);
    if (it == sess_->pluginsById.end() || it->second == nullptr) {
        warn("no such plugin in the running edit", id);
        return;
    }
    auto& plugin = *it->second;

    // Already created (visible, or hidden after a previous close) — just show it.
    if (auto w = sess_->pluginWindows.find(id); w != sess_->pluginWindows.end() && w->second) {
        raiseToFront(*w->second);
        return;
    }

    // Only external plugins wrap a juce::AudioProcessor with a native editor; built-ins return null here.
    auto* proc = plugin.getWrappedAudioProcessor();
    if (proc == nullptr) {
        warn("'" + plugin.getName().toStdString() + "' is a built-in with no native UI", id);
        return;
    }
    if (!proc->hasEditor()) {
        warn("plugin '" + plugin.getName().toStdString() + "' has no editor", id);
        return;
    }
    auto* editor = proc->createEditorIfNeeded();
    if (editor == nullptr) {
        warn("could not create an editor for '" + plugin.getName().toStdString() + "'", id);
        return;
    }
    // An icon matching the plugin, and the autosave baseline seeded with the state as loaded so the first tick saves only a real change.
    juce::Image icon;
    if (auto* inst = dynamic_cast<juce::AudioPluginInstance*>(proc)) {
        icon = pluginIconFor(inst->getPluginDescription());
        inst->getStateInformation(sess_->lastSavedState[id]);
    }
    if (!icon.isValid())
        icon = studioIcon();
    // The autosave/close lambda re-binds through the Impl, which outlives the window — not through this transient.
    sess_->pluginWindows[id] =
        std::make_unique<PluginWindow>(plugin.getName(), editor, icon,
                                       [im = &impl_, id, sid = session_] { PluginEditorController(*im, sid).persist(id); });
}

// Persist a plugin's state, preferring text params and falling back to the module's own .vstpreset — docs/pluginEditors.md.
void PluginEditorController::persist(const std::string& id) {
    if (sess_ == nullptr) return;
    auto pl = sess_->pluginsById.find(id);
    auto sp = sess_->presetSaveById.find(id);
    if (pl == sess_->pluginsById.end() || pl->second == nullptr || sp == sess_->presetSaveById.end())
        return;
    auto& plugin = *pl->second;

    // Skip when nothing changed since the last save (autosave idle no-op).
    if (auto* ext = dynamic_cast<te::ExternalPlugin*>(&plugin))
        if (auto* inst = ext->getAudioPluginInstance()) {
            juce::MemoryBlock cur;
            inst->getStateInformation(cur);
            auto& last = sess_->lastSavedState[id];
            if (cur.getSize() > 0 && cur == last)
                return;
            last = cur;
        }

    if (sess_->edit && paramsCompleteForLive(*sess_->edit, plugin, sess_->paramProbes[id])) {
        juce::File(juce::String(sp->second)).deleteFile();   // text params supersede it
        if (impl_.pluginParamsCb)
            impl_.pluginParamsCb(session_, id, paramsJson(plugin).toStdString());
        return;
    }

    const juce::File file{juce::String(sp->second)};
    if (saveVstPreset(plugin, file)) {
        if (impl_.presetSavedCb)
            impl_.presetSavedCb(session_, id, sp->second);
    } else {
        warn("could not save preset to " + sp->second, id);
    }
}

std::vector<std::pair<std::string, te::ExternalPlugin*>>
PluginEditorController::moduleInstances(const std::string& module) const {
    std::vector<std::pair<std::string, te::ExternalPlugin*>> out;
    if (sess_ == nullptr) return out;
    for (auto& [id, pl] : sess_->pluginsById) {
        if (pl == nullptr) continue;
        // The id is "<chain>:<module>" and an INSTANCE carries a colon of its own, so split on the FIRST colon, never the last.
        const auto colon = id.find(':');
        const std::string mod = colon == std::string::npos ? id : id.substr(colon + 1);
        if (mod == module)
            if (auto* ext = dynamic_cast<te::ExternalPlugin*>(pl.get()))
                out.emplace_back(id, ext);
    }
    return out;
}

// The presets a module's external plugin offers: its program list, plus every .vstpreset in the standard folders.
std::vector<EngineHost::PresetInfo>
PluginEditorController::listPresets(const std::string& module) {
    const auto insts = moduleInstances(module);
    if (insts.empty()) return {};
    auto* inst = insts.front().second->getAudioPluginInstance();
    if (inst == nullptr) return {};

    std::vector<EngineHost::PresetInfo> out;

    // Skip a lone or absent program list, and JUCE's dummy 128-entry "ProgramChange N" one — docs/pluginEditors.md.
    const int nprog = inst->getNumPrograms();
    const bool genericProgramList =
        nprog > 0 &&
        inst->getProgramName(0).trim().startsWithIgnoreCase("ProgramChange");
    if (nprog > 1 && !genericProgramList)
        for (int i = 0; i < nprog; ++i) {
            std::string name = inst->getProgramName(i).toStdString();
            if (name.empty()) name = "Program " + std::to_string(i + 1);
            out.push_back({name, "program", i, {}});
        }

    // .vstpreset files, under Steinberg's <root>/VST3 Presets/<Vendor>/<Plugin>/… — recursive, since vendors nest presets by category.
    const auto desc = inst->getPluginDescription();
    const juce::String sub{"VST3 Presets"};
    juce::Array<juce::File> roots;
    for (auto loc : {juce::File::userDocumentsDirectory,
                     juce::File::commonDocumentsDirectory,
                     juce::File::userApplicationDataDirectory,
                     juce::File::commonApplicationDataDirectory})
        roots.add(juce::File::getSpecialLocation(loc)
                      .getChildFile(sub)
                      .getChildFile(desc.manufacturerName)
                      .getChildFile(desc.name));
    if (const auto cpf =
            juce::SystemStats::getEnvironmentVariable("CommonProgramFiles", {});
        cpf.isNotEmpty())
        roots.add(juce::File(cpf)
                      .getChildFile(sub)
                      .getChildFile(desc.manufacturerName)
                      .getChildFile(desc.name));

    juce::StringArray seen;
    for (const auto& root : roots) {
        if (!root.isDirectory()) continue;
        for (const auto& f :
             root.findChildFiles(juce::File::findFiles, true, "*.vstpreset")) {
            const auto abs = f.getFullPathName();
            if (seen.contains(abs)) continue;
            seen.add(abs);
            out.push_back({f.getFileNameWithoutExtension().toStdString(), "file", -1,
                           abs.toStdString()});
        }
    }
    return out;
}

// Apply a preset to every live instance of the module, then persist it to the module's own .vstpreset.
void PluginEditorController::setPreset(const std::string& module, int programIndex,
                                       const std::string& presetPath) {
    const auto insts = moduleInstances(module);
    if (insts.empty()) return;
    for (const auto& [id, ext] : insts) {
        if (!presetPath.empty()) {
            loadVstPreset(*ext, juce::File(juce::String(presetPath)));
        } else if (auto* inst = ext->getAudioPluginInstance()) {
            if (programIndex >= 0 && programIndex < inst->getNumPrograms())
                inst->setCurrentProgram(programIndex);
        }
    }
    // The instances share the module's .vstpreset, so one persist covers them all and broadcasts preset-saved once.
    persist(insts.front().first);
}

