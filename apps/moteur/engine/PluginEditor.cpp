// Whether a plugin's text params fully reproduce its state, so it can be saved as text rather than an opaque
// .vstpreset: a built-in's state IS its params, and an external's are complete iff a fresh instance carrying
// only them round-trips to the same blob. That creates a second, throwaway instance in the LIVE edit.
bool paramsCompleteForLive(te::Edit& edit, te::Plugin& plugin) {
    auto* ext = dynamic_cast<te::ExternalPlugin*>(&plugin);
    if (ext == nullptr)
        return true;
    auto* inst = ext->getAudioPluginInstance();
    if (inst == nullptr)
        return false;
    juce::MemoryBlock a;
    inst->getStateInformation(a);
    auto plugin2 = edit.getPluginCache().createNewPlugin(te::ExternalPlugin::xmlTypeName, inst->getPluginDescription());
    auto* ext2 = dynamic_cast<te::ExternalPlugin*>(plugin2.get());
    if (ext2 == nullptr)
        return false;
    applyPluginParams(*plugin2, currentParamValues(plugin));
    auto* inst2 = ext2->getAudioPluginInstance();
    if (inst2 == nullptr)
        return false;
    juce::MemoryBlock b;
    inst2->getStateInformation(b);
    return a == b;
}

